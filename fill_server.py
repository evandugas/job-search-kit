"""Local helper for the "Job Search Autofill" Chrome extension (extension/).

Serves the apply queue's tailored resume, cover letter and answers.toml to the extension, on
127.0.0.1 only and only with the token in extension/config.js. Started at logon by the scheduled task
("Job Search Kit - Fill Helper", or @reboot cron); run `python fill_server.py` by hand to see its log.
"""
import base64
import http.server
import json
import re
import secrets
import sys
import tomllib
import urllib.parse
from pathlib import Path

import apply

ROOT = Path(__file__).resolve().parent
PORT = 8765
CONFIG_JS = ROOT / "extension" / "config.js"


def token():
    if CONFIG_JS.exists() and (m := re.search(r'TOKEN: "(\w+)"', CONFIG_JS.read_text())):
        return m.group(1)
    t = secrets.token_hex(16)
    CONFIG_JS.write_text(f"// Generated by fill_server.py; must match the helper's token.\n"
                         f"const JS_FILL = {{ PORT: {PORT}, TOKEN: \"{t}\" }};\n")
    return t


def job_keys(url):
    """Pieces of a posting URL that also appear in its application page's URL: Workday's
    '<slug>_<req id>' segment, Greenhouse/LinkedIn numeric ids, Lever/Ashby UUIDs."""
    u = urllib.parse.urlparse(url)
    parts = [p for p in u.path.split("/") if p]
    parts += [v for vals in urllib.parse.parse_qs(u.query).values() for v in vals]
    return {p.lower() for p in parts if len(p) >= 6 and re.search(r"\d", p)}


def find_match(page_url, q):
    page = urllib.parse.unquote(page_url).lower()
    for k, v in q.items():
        if v["status"] == "to apply" and any(key in page for key in job_keys(v["url"])):
            return k
    return None


def cover_text(docx_path):
    try:
        from docx import Document
        paras = [p.text for p in Document(docx_path).paragraphs if p.text.strip()]
        body = paras[2:]  # skip the name + contact header, then the date line
        if body and re.match(r"[A-Z][a-z]+ \d{1,2}, \d{4}$", body[0]):
            body = body[1:]
        return "\n\n".join(body)
    except Exception:
        return ""


def file_payload(path):
    p = Path(path) if path else None
    if not p or not p.exists():
        return None
    return {"name": p.name, "type": "application/pdf", "b64": base64.b64encode(p.read_bytes()).decode()}


def answers():
    path = ROOT / "answers.toml"
    return tomllib.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


class Handler(http.server.BaseHTTPRequestHandler):
    def send(self, code, obj):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if not secrets.compare_digest(self.headers.get("X-JS-Token", ""), TOKEN):
            return self.send(403, {"error": "bad token"})
        u = urllib.parse.urlparse(self.path)
        qs = {k: v[0] for k, v in urllib.parse.parse_qs(u.query).items()}
        q = apply.load()
        if u.path == "/match":
            jobs = sorted(({"id": k, "company": v["company"], "title": v["title"], "score": v.get("score")}
                           for k, v in q.items() if v["status"] == "to apply"), key=lambda j: -(j["score"] or 0))
            return self.send(200, {"match": find_match(qs.get("url", ""), q), "jobs": jobs, "answers": answers()})
        if u.path == "/job" and qs.get("id") in q:
            v = q[qs["id"]]
            return self.send(200, {"id": qs["id"], "company": v["company"], "title": v["title"],
                                   "why_interested": v.get("why_interested", ""),
                                   "salary_range": v.get("salary_range") or apply.salary_range(v.get("description")),
                                   "cover_text": cover_text(v.get("cover_docx")),
                                   "resume": file_payload(v.get("resume_pdf")), "cover": file_payload(v.get("cover_pdf"))})
        if u.path == "/done" and qs.get("id") in q:
            v = q[qs["id"]]
            v["status"], v["applied_on"] = "applied", apply.dt.date.today().isoformat()
            apply.save(q)
            return self.send(200, {"ok": True})
        self.send(404, {"error": "not found"})

    def log_message(self, fmt, *args):
        if sys.stdout:
            sys.stdout.write("%s\n" % (fmt % args))


TOKEN = token()

if __name__ == "__main__":
    print(f"Job Search fill helper on http://127.0.0.1:{PORT}")
    http.server.ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
